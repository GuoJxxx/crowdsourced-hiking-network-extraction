function index = tracebundle_build_endpoint_grid(slk, cell_size_m)
%TRACEBUNDLE_BUILD_ENDPOINT_GRID Build a sparse deterministic endpoint grid.
%   The index stores only occupied cells.  It never decides whether a
%   segment belongs to a query polygon; the public inpolygon calls retain
%   that responsibility.

if ~isnumeric(slk) || ~isreal(slk) || ndims(slk) ~= 2 || size(slk, 2) < 4
    error('tracebundle:grid:InvalidSegments', ...
        'slk must be a real numeric N-by-at-least-4 matrix');
end
if ~isnumeric(cell_size_m) || ~isreal(cell_size_m) || ...
        ~isscalar(cell_size_m) || ~isfinite(cell_size_m) || cell_size_m <= 0
    error('tracebundle:grid:InvalidCellSize', ...
        'cell_size_m must be a positive finite scalar');
end

coordinates = slk(:, 1:4);
if any(~isfinite(coordinates(:)))
    error('tracebundle:grid:NonfiniteSegments', ...
        'slk endpoint coordinates must be finite');
end

if isempty(slk)
    index = struct( ...
        'format_version', 1, ...
        'cell_size_m', double(cell_size_m), ...
        'origin_x', 0.0, ...
        'origin_y', 0.0, ...
        'grid_width', 1.0, ...
        'max_ix', -1.0, ...
        'max_iy', -1.0, ...
        'occupied_keys', zeros(0, 1, 'uint64'), ...
        'offsets', ones(1, 1), ...
        'segment_ids', zeros(0, 1));
    return;
end

segment_count = size(slk, 1);
x = [slk(:, 1); slk(:, 3)];
y = [slk(:, 2); slk(:, 4)];
origin_x = floor(min(x) / cell_size_m) * cell_size_m;
origin_y = floor(min(y) / cell_size_m) * cell_size_m;
ix = floor((x - origin_x) / cell_size_m);
iy = floor((y - origin_y) / cell_size_m);
grid_width = max(ix) + 1;

cell_keys = ix + iy * grid_width + 1;
segment_ids = [(1:segment_count)'; (1:segment_count)'];
pairs = sortrows([cell_keys, segment_ids], [1, 2]);
keep = [true; any(diff(pairs, 1, 1) ~= 0, 2)];
pairs = pairs(keep, :);
starts = find([true; diff(pairs(:, 1)) ~= 0]);

index = struct( ...
    'format_version', 1, ...
    'cell_size_m', double(cell_size_m), ...
    'origin_x', double(origin_x), ...
    'origin_y', double(origin_y), ...
    'grid_width', double(grid_width), ...
    'max_ix', double(max(ix)), ...
    'max_iy', double(max(iy)), ...
    'occupied_keys', uint64(pairs(starts, 1)), ...
    'offsets', [starts; size(pairs, 1) + 1], ...
    'segment_ids', double(pairs(:, 2)));
end

